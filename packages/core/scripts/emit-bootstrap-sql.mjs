/**
 * Writes prisma/bootstrap.sqlite.sql — the DDL the core runs the first time it
 * opens an empty SQLite file.
 *
 * Not written by hand, and not to be edited by hand: it is what Prisma itself
 * produces when asked to diff an empty database against schema.prisma, so it
 * cannot drift from the schema. The only change made here is IF NOT EXISTS on
 * every CREATE, which makes the script idempotent — two processes bootstrapping
 * the same file at once cannot trip each other.
 *
 * Runs as part of `pnpm build`. Ships in the package (prisma/ is in `files`).
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const schema = path.join(root, 'prisma', 'schema.prisma');
const out = path.join(root, 'prisma', 'bootstrap.sqlite.sql');

const schemaText = fs.readFileSync(schema, 'utf8');

if (!/provider\s*=\s*"sqlite"/.test(schemaText)) {
  // The schema has been switched to PostgreSQL (scripts/set-datasource.mjs).
  // The bootstrap is SQLite-only, so the previous file is kept if there is one.
  if (fs.existsSync(out)) {
    console.log('[bootstrap-sql] schema is not sqlite; keeping the existing bootstrap.sqlite.sql');
    process.exit(0);
  }
  console.error(
    '[bootstrap-sql] schema is not sqlite and no bootstrap.sqlite.sql exists.\n' +
      '  Run `pnpm use:sqlite` and build again.'
  );
  process.exit(1);
}

// The CLI is invoked through node directly rather than through the .cmd shim,
// which would need a shell on Windows.
const prismaCli = createRequire(import.meta.url).resolve('prisma/build/index.js');

const ddl = execFileSync(
  process.execPath,
  [prismaCli, 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', schema, '--script'],
  { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }
);

const idempotent = ddl
  .replace(/CREATE TABLE "/g, 'CREATE TABLE IF NOT EXISTS "')
  .replace(/CREATE UNIQUE INDEX "/g, 'CREATE UNIQUE INDEX IF NOT EXISTS "')
  .replace(/CREATE INDEX "/g, 'CREATE INDEX IF NOT EXISTS "');

const header =
  '-- Generated by scripts/emit-bootstrap-sql.mjs from prisma/schema.prisma.\n' +
  '-- Do not edit: rebuild instead. Applied by src/bootstrap.ts the first time an\n' +
  '-- empty SQLite store is opened.\n\n';

fs.writeFileSync(out, header + idempotent.replace(/\r\n/g, '\n'), 'utf8');

const statements = idempotent.split(/;\s*\n/).filter((s) => s.replace(/^--.*$/gm, '').trim()).length;
console.log(`[bootstrap-sql] wrote ${path.relative(root, out)} (${statements} statements)`);
